#!/usr/bin/env python3
"""Review 105 R3: frame list of the ORIGINAL iPhone 12 Pro battery boot capture (POWER state) for the host replay.

Input: 07_Test_Evidence/CLAUDE_FIRST_BURST_DECODE/full_POWER.txt, Claude's own text decode of
IPHONE12PRO_BOOT_POWER_12M_500M.sr (sha256 66c7e61d...cfd5). The firmware tables (src/batt/ds12p_*.inc) were generated
by DeepSeek's generator from a different decode (DEEPSEEK_IPHONE12PRO_BOOT_073 JSONL); this file never reads them, so
the replay oracle and the served data come from two independent decodes of the same recording.

Kept (address 0x0B only):
  R  read, PEC valid, master NACKed the last byte: response bytes = data (+count for blocks) + PEC, as sent by the battery
  P  count-only probe (len=0): the one byte the battery sent (the decoder prints it in the pec= field)
  W  write, PEC valid, every byte ACKed by the battery: cmd + body + PEC
Dropped, counted in the header: frames of other addresses, reads with a PEC error (bit slips in the capture), reads the
master over-read (last=A), writes the battery NACKed.

Usage: gen_p12p_power_frames.py <full_POWER.txt> <out.inc>
"""
import hashlib, re, sys

SRC_SHA = "adcbd5fdc45a90a14a8e0eb9e9c20cfa215e5c8e6c2d4a2cca930d8fdc4ab049"
src, out = sys.argv[1], sys.argv[2]
raw = open(src, "rb").read()
sha = hashlib.sha256(raw).hexdigest()
if sha != SRC_SHA:
    sys.exit(f"source sha256 {sha} != pinned {SRC_SHA}")
text = raw.decode("utf-8-sig")

RD = re.compile(r"^\s*([\d.]+)s R addr=0x([0-9A-F]{2}) cmd=0x([0-9A-F]{2}) len=\s*(\d+) data=([0-9A-F ]*) pec=([0-9A-F]{2}) (ok|BAD) last=([NA])")
WR = re.compile(r"^\s*([\d.]+)s W addr=0x([0-9A-F]{2}) bytes=([0-9A-F ]+?)\s+(pec ok\s+)?acks=([AN]+)")
frames, drop = [], {"other_addr": 0, "read_pec_error": 0, "read_overread": 0, "write_nacked_or_bad": 0, "unparsed": 0}
for line in text.splitlines():
    if not line.strip():
        continue
    m = RD.match(line)
    if m:
        t, addr, cmd, n, data, pec, ok, last = m.groups()
        if addr != "0B": drop["other_addr"] += 1; continue
        b = [int(x, 16) for x in data.split()]
        if int(n) == 0:
            frames.append(("P", int(cmd, 16), [int(pec, 16)], t)); continue
        if ok != "ok": drop["read_pec_error"] += 1; continue
        if last != "N": drop["read_overread"] += 1; continue
        assert len(b) == int(n), line
        frames.append(("R", int(cmd, 16), b + [int(pec, 16)], t)); continue
    m = WR.match(line)
    if m:
        t, addr, data, pecok, acks = m.groups()
        if addr != "0B": drop["other_addr"] += 1; continue
        b = [int(x, 16) for x in data.split()]
        if not pecok or "N" in acks: drop["write_nacked_or_bad"] += 1; continue
        frames.append(("W", b[0], b, t)); continue
    drop["unparsed"] += 1
if drop["unparsed"]:
    sys.exit(f"{drop['unparsed']} unparsed lines")

kinds = {k: sum(1 for f in frames if f[0] == k) for k in "RPW"}
with open(out, "w", newline="\n") as f:
    f.write("/* GENERATED by tests/host/gen/gen_p12p_power_frames.py - do not edit.\n")
    f.write(f" * Source: 07_Test_Evidence/CLAUDE_FIRST_BURST_DECODE/full_POWER.txt sha256 {sha}\n")
    f.write(" *         (text decode of IPHONE12PRO_BOOT_POWER_12M_500M.sr, sha256 66c7e61d00e9d983630617f00c1f81d8d8595fbf63771a62fc26dabc6ba1cfd5)\n")
    f.write(f" * Kept: {kinds['R']} reads, {kinds['P']} count probes, {kinds['W']} writes (address 0x0B).\n")
    f.write(" * Dropped: " + ", ".join(f"{k}={v}" for k, v in drop.items() if k != "unparsed") + "\n")
    f.write(" * kind 'R': b = bytes the battery sent (data [+count] + PEC); 'P': the count byte of a count-only probe;\n")
    f.write(" * kind 'W': b = cmd + body + PEC as written by the phone. */\n")
    f.write(f"#define P12_FRAME_COUNT {len(frames)}u\n")
    f.write("static const p12_frame_t P12_FRAMES[P12_FRAME_COUNT] = {\n")
    for k, cmd, b, t in frames:
        f.write(f"    {{'{k}', 0x{cmd:02X}, {len(b)}, {{{', '.join(f'0x{x:02X}' for x in b)}}}, \"{t}\"}},\n")
    f.write("};\n")
print(len(frames), kinds, drop)
